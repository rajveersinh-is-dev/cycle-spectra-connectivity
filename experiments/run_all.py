"""Run the complete experimental pipeline and write ``results/summary.md``.

Usage
-----
    python experiments/run_all.py                # full pipeline, n <= 9
    python experiments/run_all.py --max-n 7      # faster smoke run
    python experiments/run_all.py --skip-figures

Nothing in the pipeline uses randomness; every number written to ``results/``
is produced by exact integer computation.
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import common  # noqa: E402


def summarise(results: dict) -> None:
    """Write a human-readable summary of the headline numbers."""
    lines: list[str] = []
    add = lines.append
    add("# Experimental results\n")
    add("Generated by `experiments/run_all.py`.  Every value below is produced by")
    add("exact integer computation in `src/cycle_spectra`; no sampling is involved.\n")

    add("## 1. Generators (cross-validated)\n")
    add("| order n | unlabeled 2-connected | unlabeled 3-connected |")
    add("|---:|---:|---:|")
    card = results["cardinalities"]
    two = {int(k): v for k, v in card["two_connected_counts"].items()}
    three = {int(k): v for k, v in card["three_connected_counts"].items()}
    for n in sorted(set(two) | set(three)):
        t2 = two.get(n)
        t3 = three.get(n)
        add(f"| {n} | {t2 if t2 is not None else '-'} | {t3 if t3 is not None else '-'} |")
    add("")
    add(f"Agreement with published cardinalities: **{card['agreement']}**\n")

    add("## 2. Path Lemma and Theorem A\n")
    pl = results["theorems"]["path_lemma"]
    thm = results["theorems"]["theorem_a"]
    add("| connectivity k | minimum observed | c(K_{k+1}) | extremiser degree sequence |")
    add("|---:|---:|---:|:---|")
    for k in sorted(thm["minimum_over_k_connected"], key=int):
        row = thm["minimum_over_k_connected"][k]
        add(
            f"| {k} | {row['min_cycles']} | {thm['c_complete'][str(int(k) + 1)]} | "
            f"{row['degree_sequence']} |"
        )
    add("")
    add(f"Theorem A verified exhaustively on the enumerated classes: "
        f"**{thm['theorem_a_verified']}**\n")
    add(f"Pairs (x,y) checked for the Path Lemma: **{pl['pairs_checked']}**, "
        f"violations: **{len(pl['violations'])}**\n")
    add("`Q_k` (paths between two vertices of the complete graph `K_k`):\n")
    add("| k | " + " | ".join(str(k) for k in sorted(pl["Q_table"], key=int)) + " |")
    add("|---|" + "---:|" * len(pl["Q_table"]))
    add("| Q_k | " + " | ".join(str(pl["Q_table"][k]) for k in sorted(pl["Q_table"], key=int)) + " |")
    add("")

    add("## 3. Extremal function m_3(n)\n")
    add("| n | m_3(n) | minimisers | c(W_n) | C(n-1,2) | classes examined |")
    add("|---:|---:|---:|---:|---:|---:|")
    for r in results["extremal"]["extremal_function_m3"]:
        add(
            f"| {r['n']} | {r['m3']} | {r['num_minimisers']} | {r['c_wheel']} | "
            f"{r['conjectured_lower_bound']} | {r['classes_examined']} |"
        )
    add("")
    add(f"All values respect the conjectured bound: "
        f"**{results['extremal']['all_bounds_respected']}**\n")

    add("## 4. Spectra\n")
    sp = results["spectra"]
    add(f"- `S_1` (connected graphs): {sp['S_1']}")
    add(f"- `S_2` (2-connected): |S_2| = {sp['S_2_size']}; missing in "
        f"[1,{sp['S_2_bound']}] = {sp['S_2_missing_below_bound']}")
    add(f"  - consistent with the proved exception list "
        f"{sp['S_2_published_exceptions']}: **{sp['S_2_agrees_with_published']}**")
    add(f"- `S_3` (3-connected): |S_3| = {sp['S_3_size']}; missing in "
        f"[1,{sp['S_3_bound']}] = {sp['S_3_missing_below_bound']}")
    add(f"  - equals the conjectured exception list: "
        f"**{sp['S_3_agrees_with_conjecture']}** "
        f"(orders up to {sp['max_order_examined']} were enumerated)")
    add("")

    add("## 5. Cone theorem (Theorem B)\n")
    ct = results["cone"]
    add("| base order | min c(K_1 v F) | predicted n(n-1)+1 | minimiser is the cycle | spread |")
    add("|---:|---:|---:|:---|:---|")
    for r in ct["rows"]:
        add(
            f"| {r['base_order']} | {r['min_cone_cycles']} | {r['predicted_min']} | "
            f"{r['minimiser_is_the_cycle']} | [{r['min_cone_cycles']}, {r['max_cone_cycles']}] |"
        )
    add("")
    add(f"Counting identity verified on every enumerated class: "
        f"**{ct['identity_c_K1vF_verified']}**\n")

    env = common.environment()
    add("## Provenance\n")
    add("```")
    for k in ("python", "platform", "numpy", "networkx", "igraph", "matplotlib",
              "git_commit", "seed", "randomness_used", "timestamp_utc"):
        add(f"{k}: {env[k]}")
    add("```")

    path = common.RESULTS / "summary.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  wrote {path.relative_to(common.ROOT)}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--max-n", type=int, default=9, help="largest order to enumerate")
    ap.add_argument("--skip-figures", action="store_true")
    args = ap.parse_args()

    import stage1_cardinalities
    import stage2_theorems
    import stage3_extremal
    import stage4_spectra
    import stage5_cone

    t0 = time.time()
    print(f"cycle-spectra pipeline (max_n = {args.max_n})")
    results: dict = {}
    results["cardinalities"] = stage1_cardinalities.main(args.max_n)
    results["theorems"] = stage2_theorems.main(min(args.max_n, 9))
    results["extremal"] = stage3_extremal.main(args.max_n)
    results["spectra"] = stage4_spectra.main(args.max_n)
    results["cone"] = stage5_cone.main(min(args.max_n, 8))
    if not args.skip_figures:
        import stage6_figures

        stage6_figures.main()
    summarise(results)
    print(f"done in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()